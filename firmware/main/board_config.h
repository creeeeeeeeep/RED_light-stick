/*
 * Waveshare ESP32-S3-Matrix 보드 핀 정의.
 *
 * 핀 번호가 다른 리비전을 쓰고 있다면 여기만 고치면 된다.
 * 부팅 로그의 I2C 스캔 결과로 QMI8658 주소(0x6A/0x6B)는 자동 판별한다.
 */
#pragma once

/* ---- 8x8 WS2812B RGB 매트릭스 ---- */
#define LED_GPIO            14
#define MATRIX_W            8
#define MATRIX_H            8
#define MATRIX_PIXELS       (MATRIX_W * MATRIX_H)

/*
 * 픽셀 배선 순서.
 *   MATRIX_SERPENTINE 1 : 지그재그 (0행 왼→오, 1행 오→왼, ...)
 *   MATRIX_SERPENTINE 0 : 전 행이 같은 방향 (progressive)
 * 좌우 스윕 이펙트가 톱니처럼 찢어져 보이면 이 값을 뒤집는다.
 */
#define MATRIX_SERPENTINE   0

/* 매트릭스 회전/미러 보정. 위쪽 이펙트가 아래로 흐르면 FLIP_Y를 1로. */
#define MATRIX_FLIP_X       0
#define MATRIX_FLIP_Y       0

/*
 * 전역 밝기 상한 (0~255). 감마 보정 후에 곱해진다.
 *
 * 이제 프레임마다 실제 전류를 추정해 예산을 넘으면 자동으로 줄이므로,
 * 안전을 위해 이 값을 낮게 잡을 필요가 없다. 255로 두고 전류 제한에
 * 맡기면 흰색이 아닌 대부분의 이펙트는 훨씬 밝아지고, 풀화이트처럼
 * 정말 전력을 많이 먹는 프레임만 깎인다.
 *
 * 이 값을 낮추면 남는 PWM 계조가 줄어 어두운 구간(IDLE 숨쉬기, 잔상 꼬리)이
 * 뭉개진다. 웬만하면 255로 두고 LED_BUDGET_MA 로 조절할 것.
 */
#define LED_MAX_BRIGHTNESS  255
#define LED_GAMMA           2.2f

/*
 * ---- 전류 제한 (하드 제약) ----
 *
 * WS2812 는 채널(R/G/B) 하나당 최대 약 20mA 를 먹는다.
 * 64픽셀 x 3채널 x 20mA = 약 3.8A. USB 로는 절대 못 준다.
 *
 * 렌더 직후 프레임의 실제 전류를 추정하고 LED_BUDGET_MA 를 넘으면 프레임
 * 전체에 배율을 곱해 끌어내린다. 색은 유지되고 밝기만 줄어든다.
 *
 * 예산은 급전 환경에 맞춰 정한다. MCU + WiFi 가 별도로 100~350mA 를 쓰므로
 * 포트 총량에서 그만큼 빼고 잡아야 한다.
 *
 *   급전 환경                    포트 총량   LED 예산 권장
 *   -------------------------------------------------------
 *   USB 2.0 PC 포트                500mA         300
 *   USB 3.0 PC 포트                900mA         600
 *   USB-C 충전기 / 전원 허브      1.5~3A        1200 이상
 *   배터리 + 2A 컨버터             2A           1200 이상
 *
 * 모르겠으면 300 부터 시작해 리셋이 안 나는 선까지 올린다.
 * 넘치면 대개 타는 게 아니라 전압 강하로 보드가 리셋된다.
 */
#define LED_MA_PER_CHANNEL      20.0f   /* 채널 하나의 최대 전류 */
#define LED_QUIESCENT_MA        1.0f    /* LED 하나의 대기 전류 */
/*
 * 이 값은 더 이상 직접 쓰이지 않는다. power.c 가 실행 중에 정한다 —
 * USB 호스트가 붙어 있으면 PC 로 보고 낮게, 아니면 충전기로 보고 높게 잡고,
 * 전압이 주저앉아 재부팅되면 한 단계 낮춰 기억한다.
 *
 * 고정값으로 되돌리려면 power_budget_ma() 가 이 값을 반환하게 하면 된다.
 */
#define LED_BUDGET_MA           600.0f

/* ---- QMI8658C 6축 IMU (I2C) ---- */
#define IMU_I2C_PORT        0
#define IMU_SDA_GPIO        11
#define IMU_SCL_GPIO        12
#define IMU_I2C_HZ          400000

/* ---- 전송 버튼 ---- */
/*
 * 전송 버튼. 크라운에 다는 택트 스위치를 GPIO2 패드와 GND 패드에 잇는다.
 * 내부 풀업을 켜므로 저항은 필요 없고, 누르면 LOW 다.
 *
 * GPIO0(내장 BOOT 버튼)을 그대로 쓰지 않는 이유는 그게 스트래핑 핀이기
 * 때문이다. 버튼을 누른 채로 전원이 들어오면 보드가 ROM 부트로더로 빠져서
 * 먹통처럼 보인다. 팬에게 나눠주는 물건에서는 반드시 한 번은 일어난다.
 *
 * GPIO1 은 비워둔다 — ADC1 채널이라 나중에 배터리 전압을 재기 좋다.
 *
 * 내장 버튼도 계속 읽는다. 납땜하기 전에도 테스트할 수 있어야 한다.
 * 둘 중 아무거나 눌리면 눌린 것으로 본다.
 */
#define BUTTON_GPIO         2
#define BUTTON_ONBOARD_GPIO 0
#define BUTTON_ACTIVE_LOW   1
#define BUTTON_DEBOUNCE_MS  40

/* ---- 이모티콘 큐 ---- */
/*
 * 흔들면 쌓이고 버튼을 누르면 한 번에 전송한다.
 *
 * QUEUE_MAX 는 치지직 채팅 입력창이 받아주는 이모티콘 개수 상한이다.
 * 입력창에서 이모티콘 하나는 <img> 한 개이고, 치지직은 글자 수가 아니라
 * 개수로 10개까지 제한한다 (실측). 공식 API 문서의 100자 제한은 순수
 * 텍스트 기준이라 여기엔 해당하지 않는다.
 *
 * QUEUE_ADD_INTERVAL_MS 는 "흔든 만큼 쌓인다"의 속도다. 1초에 1개면
 * 사용자가 세기 쉽고, 가득 차기까지 10초라 충분히 흔들 시간이 된다.
 * 상한은 목표가 아니라 천장이다 — 언제든 버튼을 눌러 보낼 수 있다.
 */
#define QUEUE_MAX               10
#define QUEUE_ADD_INTERVAL_MS   1000  /* 흔드는 중 이 간격마다 1개씩 쌓인다 */

/*
 * 같은 모션을 이만큼 유지해야 쌓기 시작한다.
 *
 * 봉을 집어들거나 자세를 고치는 움직임도 제스처로 잡힐 수 있다. 곧바로 한 개를
 * 먹으면 의도하지 않은 이모티콘이 큐에 들어간다. 잠깐 버티게 하면 "흔들려고
 * 마음먹은" 동작만 남는다.
 *
 * 제스처 엔진 자체의 확정 지연은 몇십 ms 밖에 안 되므로, 첫 개까지 걸리는
 * 시간은 사실상 이 값이다. 0.8초면 우연한 움직임은 걸러지면서 굼뜨게 느껴지지
 * 않는다.
 */
#define QUEUE_ARM_MS            800

/*
 * 이보다 짧게 IDLE 로 빠지는 것은 흔들기가 끊긴 것으로 보지 않는다.
 *
 * 좌우로 흔들 때 방향을 바꾸는 순간에는 실제로 거의 멈추기 때문에 판정이
 * 찰나 IDLE 로 떨어진다. 그때마다 처음부터 다시 세면 박자가 끊기고, 다시
 * 붙는 순간 한 개가 곧바로 들어가서 두 개가 잇달아 올라간 것처럼 보인다.
 *
 * 흔드는 주기가 2~5Hz 이므로 한 번 뒤집는 데 100~250ms 다. 400ms 면 그건
 * 넘기면서 진짜로 멈춘 것은 걸러낸다.
 */
#define QUEUE_GAP_MS            400

/*
 * 봉이 "살아 있다"고 서버에 알리는 주기.
 *
 * 설정 페이지가 이걸로 온라인 여부를 판단한다. 너무 잦으면 서버 로그가
 * 지저분해지고, 너무 뜸하면 껐는데도 한참 켜진 것처럼 보인다.
 */
#define STATUS_REPORT_MS    20000

/* ---- 샘플링 ---- */
#define IMU_SAMPLE_HZ       200     /* 제스처 엔진 입력 레이트 */
#define LED_FRAME_HZ        60      /* 렌더 프레임 레이트 */

